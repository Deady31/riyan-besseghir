// Capture de la démo bancaire (image de la carte projet) : node tools/qa/bank-shot.mjs [--url=…]
import { OUT, launch, parseArgs, serve, viewport } from './lib.mjs'
const { flags } = parseArgs()
const { url, stop } = await serve(flags.url)
const b = await launch()
const p = await (await b.newContext({ viewport: viewport(false) })).newPage()
const errors = []
p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${url.replace(/\/$/, '')}/projets/assistant-bancaire`, { waitUntil: 'networkidle' })
await p.waitForTimeout(2500)
const demo = p.getByRole('log').locator('xpath=..')
await demo.scrollIntoViewIfNeeded()
await p.getByRole('button', { name: /j.ai perdu ma carte/i }).first().click()
await p.waitForTimeout(1400)
await p.mouse.move(2, 2)
await p.waitForTimeout(500)
await demo.screenshot({ path: `${OUT}bank-demo-lost.png` })
await p.getByRole('button', { name: /bloquer la carte \(simulé\)/i }).click()
await p.waitForTimeout(1200)
await p.getByRole('textbox').fill('mon IBAN est FR76 3000 6000 0112 3456 7890 189, j’ai une réclamation')
await p.keyboard.press('Enter')
await p.waitForTimeout(1400)
await demo.screenshot({ path: `${OUT}bank-demo-guard.png` })
const txt = await p.getByRole('log').innerText()
console.log('IBAN visible dans le journal:', /FR76/.test(txt), '| badge masque:', /Masqué avant le modèle/.test(txt))
console.log('erreurs:', errors.length, errors.join(' | '))
await b.close()
await stop?.()
